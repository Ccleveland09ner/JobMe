/**
 * 3D lettering for words in the scene (Comic Neue Bold, SIL OFL). The font,
 * geometries and materials are built once and shared: never mutate them.
 * Words painted on things take that thing's light (finishes.ts, as a decal);
 * signs that must read as UI, like the floating labels, are unlit here.
 */

import { useLoader } from "@react-three/fiber";
import * as THREE from "three";
import { TextGeometry } from "three/examples/jsm/geometries/TextGeometry.js";
import { FontLoader, type Font } from "three/examples/jsm/loaders/FontLoader.js";

import { PALETTE, type PaletteColor } from "./palette";

/** Generated by design/tools/make-typeface.mjs. */
export const LETTERING_FONT = "/fonts/comic-neue-bold.typeface.json";

export function useLetteringFont(): Font {
  return useLoader(FontLoader, LETTERING_FONT);
}

export interface LetteringSpec {
  text: string;
  /** Cap height, roughly, in metres. */
  size: number;
  /** Extrusion depth in metres; 0 is flat paint. */
  depth: number;
  /** "center": centred on all axes. "surface": back face at z = 0, to sit on a surface. */
  anchor?: "center" | "surface";
  /** Fatten each glyph by this much (m); drawn in ink behind the letters, it's an even outline. */
  stroke?: number;
}

const geometries = new Map<string, TextGeometry>();

export function letteringGeometry(font: Font, { text, size, depth, anchor = "center", stroke = 0 }: LetteringSpec): TextGeometry {
  const key = `${text}|${size}|${depth}|${anchor}|${stroke}`;
  let geometry = geometries.get(key);
  if (!geometry) {
    const raised = depth >= size * 0.12;
    geometry = new TextGeometry(
      text,
      stroke > 0
        ? // bevelOffset pushes the whole glyph out, caps included.
          {
            font,
            size,
            depth: Math.max(depth, 0.0005),
            curveSegments: 5,
            bevelEnabled: true,
            bevelThickness: 0.0002,
            bevelSize: 0,
            bevelOffset: stroke,
            bevelSegments: 1,
          }
        : {
            font,
            size,
            depth: Math.max(depth, 0.0005),
            curveSegments: 5,
            bevelEnabled: raised,
            bevelThickness: raised ? depth * 0.3 : 0,
            bevelSize: raised ? size * 0.035 : 0,
            bevelSegments: 2,
          },
    );
    geometry.computeBoundingBox();
    const box = geometry.boundingBox!;
    const cx = (box.min.x + box.max.x) / 2;
    const cy = (box.min.y + box.max.y) / 2;
    const cz = anchor === "center" ? (box.min.z + box.max.z) / 2 : box.min.z;
    geometry.translate(-cx, -cy, -cz);
    geometry.computeBoundingBox();
    geometries.set(key, geometry);
  }
  return geometry;
}

/** The width of a geometry's lettering, for laying words out. */
export function letteringWidth(geometry: THREE.BufferGeometry): number {
  const box = geometry.boundingBox;
  return box ? box.max.x - box.min.x : 0;
}

const signs = new Map<PaletteColor, THREE.MeshBasicMaterial>();

/** A flat palette colour that light and tone mapping leave alone, for signs. */
export function signMaterial(color: PaletteColor): THREE.MeshBasicMaterial {
  let material = signs.get(color);
  if (!material) {
    material = new THREE.MeshBasicMaterial({
      color: PALETTE[color],
      toneMapped: false,
      polygonOffset: true,
      polygonOffsetFactor: -1,
      polygonOffsetUnits: -1,
    });
    signs.set(color, material);
  }
  return material;
}

const pairs = new Map<string, THREE.MeshBasicMaterial[]>();

/** [face, sides] sign materials for lettering. */
export function letteringMaterials(face: PaletteColor, side: PaletteColor): THREE.MeshBasicMaterial[] {
  const key = `${face}|${side}`;
  let pair = pairs.get(key);
  if (!pair) {
    pair = [signMaterial(face), signMaterial(side)];
    pairs.set(key, pair);
  }
  return pair;
}
